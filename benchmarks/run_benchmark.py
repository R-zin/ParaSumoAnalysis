#!/usr/bin/env python3
"""Reproducible serial-vs-OpenMP benchmark harness for SumoPara.

For every dataset size x every thread count it runs the two C++ analyzer
binaries (computation time only; file I/O is excluded inside the binaries),
collects the machine-readable BENCH lines, computes

    speedup    S(p) = T(1) / T(p)
    efficiency E(p) = S(p) / p

and writes results/benchmark_results.csv plus a Markdown summary table and
SVG graphs (via benchmarks/plot_results.py, stdlib-only).

All numbers come from actually executing the binaries -- nothing here is
fabricated. Run multiple times to see run-to-run variance; the harness
reports the MEDIAN over repetitions (plus min/max spread) per cell.

Usage:
    python3 benchmarks/run_benchmark.py [--build-dir build] [--quick]
"""

import argparse
import csv
import os
import platform
import re
import statistics
import subprocess
import sys
import time

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS_DIR = os.path.join(REPO_ROOT, "benchmarks", "results")
GRAPHS_DIR = os.path.join(REPO_ROOT, "benchmarks", "graphs")

# Dataset registry: (label, path, vehicle_count). Files are generated by
# tools/generate_dataset.cpp when missing.
DATASETS = [
    ("10K", "data/small.csv", 10_000),
    ("100K", "data/medium.csv", 100_000),
    ("1M", "data/large.csv", 1_000_000),
    ("5M", "data/xlarge_5m.csv", 5_000_000),
    ("10M", "data/xlarge_10m.csv", 10_000_000),
]
QUICK_DATASETS = DATASETS[:3]  # 10K / 100K / 1M

THREAD_COUNTS = [1, 2, 4, 8]

BENCH_RE = re.compile(
    r"BENCH\s+(?P<impl>\w+)\s+threads=(?P<threads>\d+)\s+"
    r"iterations=(?P<iters>\d+)\s+best_s=(?P<best>[0-9.eE+-]+)\s+"
    r"mean_s=(?P<mean>[0-9.eE+-]+)")


def find_binary(build_dir, name):
    for candidate in (
        os.path.join(build_dir, name),
        os.path.join(build_dir, "Release", name),      # MSVC multi-config
        os.path.join(build_dir, "bin", name),
    ):
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    sys.exit(f"error: cannot find executable '{name}' under {build_dir!r}; "
             f"build the project first (cmake --build {build_dir})")


def run_timed(binary, args, inner_iterations):
    """Run one timed experiment; return the reported best-of-N time in seconds."""
    cmd = [binary, *args, "--bench", "--iterations", str(inner_iterations)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"error: benchmark command failed ({proc.returncode}): "
                 f"{' '.join(cmd)}\n{proc.stderr}")
    match = BENCH_RE.search(proc.stdout)
    if not match:
        sys.exit(f"error: no BENCH line in output of {' '.join(cmd)}\n"
                 f"{proc.stdout}")
    return float(match.group("best")), int(match.group("threads"))


def ensure_dataset(path, count, generator):
    full = os.path.join(REPO_ROOT, path)
    if not os.path.isfile(full):
        print(f"  generating {path} ({count:,} vehicles) ...", flush=True)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        subprocess.run([generator, str(count), full], check=True)
    return full


def hardware_report():
    lines = [
        f"- Date (UTC): {time.strftime('%Y-%m-%d %H:%M:%S', time.gmtime())}",
        f"- Machine: {platform.machine()} / {platform.processor() or 'unknown'}",
        f"- System: {platform.system()} {platform.release()}",
        f"- Python: {platform.python_version()}",
    ]
    try:
        brand = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"],
                               capture_output=True, text=True).stdout.strip()
        ncpu = subprocess.run(["sysctl", "-n", "hw.ncpu"],
                              capture_output=True, text=True).stdout.strip()
        mem = subprocess.run(["sysctl", "-n", "hw.memsize"],
                             capture_output=True, text=True).stdout.strip()
        lines.append(f"- CPU: {brand}, {ncpu} logical cores, "
                     f"{int(mem) / 2**30:.0f} GiB RAM")
    except Exception:
        pass
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", default=os.path.join(REPO_ROOT, "build"))
    parser.add_argument("--quick", action="store_true",
                        help="only the 10K/100K/1M datasets")
    parser.add_argument("--repetitions", type=int, default=7,
                        help="outer repetitions per cell (median is reported)")
    args = parser.parse_args()

    build_dir = os.path.abspath(args.build_dir)
    serial_bin = find_binary(build_dir, "traffic_analysis_serial")
    openmp_bin = find_binary(build_dir, "traffic_analysis_openmp")
    generator = find_binary(build_dir, "generate_dataset")

    datasets = QUICK_DATASETS if args.quick else DATASETS

    # Inner iterations amortize timer noise for tiny workloads; outer
    # repetitions capture run-to-run variance. Both scale down for big data.
    def inner_iterations(count):
        if count <= 10_000:
            return 200
        if count <= 100_000:
            return 50
        if count <= 1_000_000:
            return 20
        if count <= 5_000_000:
            return 7
        return 5

    os.makedirs(RESULTS_DIR, exist_ok=True)
    # row: (dataset, threads, median_s, min_s, max_s, serial_s,
    #       speedup_vs_serial, speedup_vs_omp1, efficiency_vs_serial)
    rows = []

    print("=== SumoPara benchmark ===")
    print(hardware_report())
    print(f"binaries: {os.path.basename(serial_bin)}, "
          f"{os.path.basename(openmp_bin)}")
    print(f"repetitions per cell: {args.repetitions} (median reported)\n")

    for label, rel_path, count in datasets:
        path = ensure_dataset(rel_path, count, generator)
        iters = inner_iterations(count)
        print(f"[{label}] {count:,} vehicles, {iters} inner iterations")

        serial_times = []
        thread_times = {t: [] for t in THREAD_COUNTS}
        for rep in range(args.repetitions):
            t_s, _ = run_timed(serial_bin, [path], iters)
            serial_times.append(t_s)
            for threads in THREAD_COUNTS:
                t_p, used = run_timed(openmp_bin,
                                      [path, "--threads", str(threads)], iters)
                if used != threads:
                    print(f"  warning: requested {threads} threads, "
                          f"runtime used {used}")
                thread_times[threads].append(t_p)

        # Two honest baselines, both reported:
        #   t_serial  = the dedicated serial program (the textbook T(1))
        #   t_omp1    = the OpenMP kernel restricted to one thread, which
        #               isolates the pure parallel-scaling behaviour from the
        #               constant cost of entering an OpenMP parallel region.
        t_serial = statistics.median(serial_times)
        t_omp1 = statistics.median(thread_times[1])
        for threads in THREAD_COUNTS:
            samples = thread_times[threads]
            tp = statistics.median(samples)
            speedup_serial = t_serial / tp if tp > 0 else 0.0
            speedup_omp1 = t_omp1 / tp if tp > 0 else 0.0
            efficiency = speedup_serial / threads
            rows.append((label, threads, tp, min(samples), max(samples),
                         t_serial, speedup_serial, speedup_omp1, efficiency))
            print(f"  threads={threads:2d}  median={tp:8.6f}s  "
                  f"S_vs_serial={speedup_serial:5.2f}x  "
                  f"S_vs_omp1={speedup_omp1:5.2f}x  "
                  f"eff(vs serial)={efficiency:5.1%}  "
                  f"(min={min(samples):.6f} max={max(samples):.6f})")
        print()

    # ---- CSV --------------------------------------------------------------
    csv_path = os.path.join(RESULTS_DIR, "benchmark_results.csv")
    with open(csv_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["dataset", "threads", "time_median_s", "time_min_s",
                         "time_max_s", "serial_time_s", "speedup_vs_serial",
                         "speedup_vs_omp1", "efficiency_vs_serial"])
        for (dataset, threads, tp, tmin, tmax, tser, s_ser, s_omp1,
             eff) in rows:
            writer.writerow([dataset, threads, f"{tp:.9f}", f"{tmin:.9f}",
                             f"{tmax:.9f}", f"{tser:.9f}", f"{s_ser:.4f}",
                             f"{s_omp1:.4f}", f"{eff:.4f}"])
    print(f"wrote {csv_path}")

    # ---- Markdown summary -------------------------------------------------
    md_path = os.path.join(RESULTS_DIR, "benchmark_summary.md")
    with open(md_path, "w") as f:
        f.write("# Benchmark results (auto-generated, measured)\n\n")
        f.write("Environment:\n" + hardware_report() + "\n\n")
        f.write("Timing = pure computation (CSV I/O excluded), median of "
                f"{args.repetitions} repetitions of best-of-N inner runs.\n\n")
        f.write("Two baselines are reported: **S(serial)** uses the dedicated "
                "serial program as T(1); **S(omp1)** uses the OpenMP kernel "
                "restricted to one thread, isolating pure scaling from the "
                "fixed cost of entering an OpenMP parallel region. "
                "Efficiency uses the serial baseline.\n\n")
        f.write("| Dataset | Serial (s) | Threads | Time (s) | S(serial) | "
                "S(omp1) | Efficiency |\n")
        f.write("|---------|-----------|---------|----------|-----------|"
                "---------|------------|\n")
        for (dataset, threads, tp, _, _, tser, s_ser, s_omp1, eff) in rows:
            f.write(f"| {dataset} | {tser:.6f} | {threads} | {tp:.6f} | "
                    f"{s_ser:.2f} | {s_omp1:.2f} | {eff:.1%} |\n")
    print(f"wrote {md_path}")

    # ---- Graphs ------------------------------------------------------------
    plot_script = os.path.join(REPO_ROOT, "benchmarks", "plot_results.py")
    if os.path.isfile(plot_script):
        subprocess.run([sys.executable, plot_script, csv_path, GRAPHS_DIR],
                       check=True)
        print(f"wrote graphs under {GRAPHS_DIR}")

    print("\nDone. All numbers above are measured, not fabricated.")


if __name__ == "__main__":
    main()
